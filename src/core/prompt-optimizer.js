/**
 * PromptOptimizer
 * Integration layer between prompt-engineer.ts and the new token-efficient
 * PromptTemplate/PromptRenderer system. Provides optimization, validation,
 * and token management for existing prompt generation workflows.
 */

const { PromptTemplate } = require('../prompt/template');
const { PromptRenderer, FallbackStrategy } = require('../prompt/renderer');

/**
 * Optimize and validate a generated meta-prompt
 */
class PromptOptimizer {
  /**
   * @param {object} options - Optimizer configuration
   * @param {number} options.maxTokens - Maximum token limit (default: 256)
   * @param {boolean} options.enforceLimit - Throw error if exceeded (default: false)
   * @param {boolean} options.singleLine - Convert to single line (default: true)
   */
  constructor(options = {}) {
    this.maxTokens = options.maxTokens || 256;
    this.enforceLimit = options.enforceLimit || false;
    this.singleLine = options.singleLine !== false;
  }

  /**
   * Optimize a meta-prompt generated by PromptEngineer
   * @param {string} metaPrompt - Raw meta-prompt text
   * @param {object} variables - Optional variables for template rendering
   * @returns {object} Optimized result with { prompt, tokenCount, warnings, optimized }
   */
  optimizeMetaPrompt(metaPrompt, variables = {}) {
    const warnings = [];
    let optimized = false;

    // Step 1: Detect if prompt has template variables
    const hasVariables = PromptTemplate.hasPlaceholders(metaPrompt);

    if (hasVariables && Object.keys(variables).length > 0) {
      // Use template rendering for variable substitution
      try {
        const template = new PromptTemplate(metaPrompt, {
          maxTokens: this.maxTokens,
        });
        
        const renderer = new PromptRenderer(template);
        const result = renderer.renderWithValidation(variables, {
          singleLine: this.singleLine,
          enforceTokenLimit: this.enforceLimit,
          truncateIfExceeds: !this.enforceLimit,
          fallbackStrategy: FallbackStrategy.EMPTY,
        });

        return {
          prompt: result.prompt,
          tokenCount: result.tokenCount,
          warnings: result.warnings,
          optimized: true,
          withinLimit: result.withinLimit,
        };
      } catch (err) {
        warnings.push(`Template optimization failed: ${err.message}`);
        // Fall through to direct optimization
      }
    }

    // Step 2: Direct optimization without template rendering
    return this.optimizeDirectly(metaPrompt, warnings);
  }

  /**
   * Optimize prompt directly without template rendering
   * @param {string} prompt - Raw prompt text
   * @param {string[]} warnings - Accumulator for warnings
   * @returns {object} Optimization result
   */
  optimizeDirectly(prompt, warnings = []) {
    let optimized = prompt;
    let didOptimize = false;

    // Remove excessive whitespace
    const beforeWhitespace = optimized;
    optimized = optimized.replace(/\s+/g, ' ').trim();
    if (optimized !== beforeWhitespace) didOptimize = true;

    // Convert to single line if requested
    if (this.singleLine) {
      const beforeSingleLine = optimized;
      optimized = optimized
        .split('\n')
        .map((line) => line.trim())
        .filter((line) => line.length > 0)
        .join(' ')
        .replace(/\s+/g, ' ')
        .trim();
      if (optimized !== beforeSingleLine) didOptimize = true;
    }

    // Estimate token count
    const tokenCount = this.estimateTokenCount(optimized);
    const withinLimit = tokenCount <= this.maxTokens;

    if (!withinLimit) {
      warnings.push(
        `Prompt exceeds token limit: ${tokenCount} > ${this.maxTokens}`
      );

      if (this.enforceLimit) {
        throw new Error(
          `Prompt exceeds token limit: ${tokenCount} > ${this.maxTokens}. ` +
          `Reduce content by ${tokenCount - this.maxTokens} tokens.`
        );
      }

      // Truncate if needed
      const targetChars = Math.floor((this.maxTokens / tokenCount) * optimized.length * 0.95);
      optimized = `${optimized.substring(0, targetChars)}...`;
      warnings.push(`Prompt truncated to fit ${this.maxTokens} token limit`);
      didOptimize = true;
    }

    return {
      prompt: optimized,
      tokenCount: this.estimateTokenCount(optimized),
      warnings,
      optimized: didOptimize,
      withinLimit: tokenCount <= this.maxTokens,
    };
  }

  /**
   * Estimate token count using same algorithm as PromptTemplate
   * @param {string} text - Text to count
   * @returns {number} Estimated token count
   */
  estimateTokenCount(text) {
    if (!text || typeof text !== 'string') return 0;
    const charCount = [...text].length;
    return Math.ceil(charCount / 4);
  }

  /**
   * Validate that a prompt meets token requirements
   * @param {string} prompt - Prompt to validate
   * @returns {object} Validation result
   */
  validatePrompt(prompt) {
    const tokenCount = this.estimateTokenCount(prompt);
    const withinLimit = tokenCount <= this.maxTokens;
    const errors = [];
    const warnings = [];

    if (!prompt || prompt.trim().length === 0) {
      errors.push('Prompt is empty');
    }

    if (!withinLimit) {
      const message = `Prompt exceeds token limit: ${tokenCount} > ${this.maxTokens}`;
      if (this.enforceLimit) {
        errors.push(message);
      } else {
        warnings.push(message);
      }
    }

    // Check for suspicious patterns
    if (prompt.includes('undefined') || prompt.includes('null')) {
      warnings.push('Prompt contains suspicious literal "undefined" or "null"');
    }

    return {
      valid: errors.length === 0,
      tokenCount,
      withinLimit,
      errors,
      warnings,
    };
  }

  /**
   * Extract key sections from a structured meta-prompt
   * @param {string} metaPrompt - Structured meta-prompt
   * @returns {object} Extracted sections
   */
  extractSections(metaPrompt) {
    const sections = {
      objective: '',
      architecture: '',
      quality: '',
      nextSteps: '',
    };

    // Extract Clear Technical Objective
    const objectiveMatch = metaPrompt.match(
      /Clear Technical Objective\s*\n([\s\S]*?)(?=\n\s*Key Files|$)/i
    );
    if (objectiveMatch) {
      sections.objective = objectiveMatch[1].trim();
    }

    // Extract Key Files / Architecture
    const archMatch = metaPrompt.match(
      /Key Files\s*\/\s*Architecture\s*\n([\s\S]*?)(?=\n\s*Quality Requirements|$)/i
    );
    if (archMatch) {
      sections.architecture = archMatch[1].trim();
    }

    // Extract Quality Requirements
    const qualityMatch = metaPrompt.match(
      /Quality Requirements\s*(?:&|and)\s*AST Verification\s*\n([\s\S]*?)(?=\n\s*Next Steps|$)/i
    );
    if (qualityMatch) {
      sections.quality = qualityMatch[1].trim();
    }

    // Extract Next Steps
    const nextStepsMatch = metaPrompt.match(
      /Next Steps\s*(?:&|and)\s*Continuation Roadmap\s*\n([\s\S]*?)$/i
    );
    if (nextStepsMatch) {
      sections.nextSteps = nextStepsMatch[1].trim();
    }

    return sections;
  }

  /**
   * Create a template-based prompt from variables
   * Useful for creating reusable prompt templates
   * @param {string} templateString - Template with {{placeholders}}
   * @param {object} variables - Variables to inject
   * @param {object} options - Rendering options
   * @returns {string} Rendered prompt
   */
  static createFromTemplate(templateString, variables, options = {}) {
    const template = new PromptTemplate(templateString, {
      maxTokens: options.maxTokens || 256,
      locale: options.locale || 'en-US',
    });

    const renderer = new PromptRenderer(template);
    return renderer.render(variables, {
      singleLine: options.singleLine !== false,
      enforceTokenLimit: options.enforceLimit || false,
      truncateIfExceeds: !options.enforceLimit,
      fallbackStrategy: options.fallbackStrategy || FallbackStrategy.EMPTY,
    });
  }

  /**
   * Batch optimize multiple prompts
   * @param {string[]} prompts - Array of prompts to optimize
   * @returns {object[]} Array of optimization results
   */
  batchOptimize(prompts) {
    return prompts.map((prompt) => this.optimizeMetaPrompt(prompt));
  }

  /**
   * Get token budget remaining for additional content
   * @param {string} prompt - Current prompt
   * @returns {number} Remaining tokens available
   */
  getRemainingTokenBudget(prompt) {
    const used = this.estimateTokenCount(prompt);
    return Math.max(0, this.maxTokens - used);
  }

  /**
   * Check if additional text can fit within token budget
   * @param {string} currentPrompt - Current prompt text
   * @param {string} additionalText - Text to add
   * @returns {boolean} True if addition fits within limit
   */
  canAddContent(currentPrompt, additionalText) {
    const currentTokens = this.estimateTokenCount(currentPrompt);
    const additionalTokens = this.estimateTokenCount(additionalText);
    return (currentTokens + additionalTokens) <= this.maxTokens;
  }
}

/**
 * Helper: Create optimizer with common presets
 */
class OptimizerPresets {
  static strict() {
    return new PromptOptimizer({
      maxTokens: 256,
      enforceLimit: true,
      singleLine: true,
    });
  }

  static lenient() {
    return new PromptOptimizer({
      maxTokens: 256,
      enforceLimit: false,
      singleLine: true,
    });
  }

  static multiline() {
    return new PromptOptimizer({
      maxTokens: 256,
      enforceLimit: false,
      singleLine: false,
    });
  }

  static extended() {
    return new PromptOptimizer({
      maxTokens: 512,
      enforceLimit: false,
      singleLine: true,
    });
  }
}

module.exports = {
  PromptOptimizer,
  OptimizerPresets,
};
